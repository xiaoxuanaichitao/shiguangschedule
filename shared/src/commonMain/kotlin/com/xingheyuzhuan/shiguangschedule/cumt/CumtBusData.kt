    fun getTimes(campus: BusCampus, line: BusLine, dayType: BusDayType): List<String> {
        return when (dayType) {
            BusDayType.WORKDAY -> when (campus) {
                BusCampus.NANHU -> if (line == BusLine.NORTH) nNorthWork else nSouthWork
                BusCampus.WENCHANG -> if (line == BusLine.NORTH) wNorthWork else wSouthWork
            }
            BusDayType.WEEKEND -> when (campus) {
                BusCampus.NANHU -> nRest
                BusCampus.WENCHANG -> wRest
            }
        }
    }

    /**
     * 计算距离指定班次发车的分钟差（仅 0..60 分钟内的即将发车返回非空值）
     */
    fun getSoonMinutes(timeText: String, nowHour: Int, nowMinute: Int): Int? {
        val parts = timeText.split(":")
        if (parts.size != 2) return null
        val h = parts[0].toIntOrNull() ?: return null
        val m = parts[1].toIntOrNull() ?: return null
        val diff = (h - nowHour) * 60 + (m - nowMinute)
        return if (diff in 0..60) diff else null
    }
